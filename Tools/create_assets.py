"""Generate mod assets with UnrealEditor-Cmd -run=pythonscript -script=<this file>."""
import unreal

ROOT = '/InstantVolumeReducer'
tools = unreal.AssetToolsHelpers.get_asset_tools()

def asset(name, path, cls, factory):
    existing = unreal.load_asset(path + '/' + name)
    return existing or tools.create_asset(name, path, cls, factory)

config_factory = unreal.BlueprintFactory()
config_factory.set_editor_property('parent_class', unreal.ModConfiguration)
bp = asset('IVR_Config', ROOT, unreal.Blueprint, config_factory)
cdo = unreal.get_default_object(bp.generated_class())
cdo.set_editor_property('config_id', unreal.ConfigId(mod_reference='InstantVolumeReducer'))
cdo.set_editor_property('display_name', 'Instant Volume Reducer')
cdo.set_editor_property('description', 'Toggle a temporary master-volume reduction during gameplay. Rebind the toggle in Options > Controls.')
section_cls = unreal.load_class(None, '/SML/Interface/UI/Menu/Mods/ConfigProperties/BP_ConfigPropertySection.BP_ConfigPropertySection_C')
integer_cls = unreal.load_class(None, '/SML/Interface/UI/Menu/Mods/ConfigProperties/BP_ConfigPropertyInteger.BP_ConfigPropertyInteger_C')
section = unreal.new_object(section_cls, outer=cdo, name='RootSection')
section.set_editor_property('requires_world_reload', False)
value = unreal.new_object(integer_cls, outer=section, name='ReductionPercent')
value.set_editor_property('requires_world_reload', False)
value.set_editor_property('display_name', 'Master volume reduction (%)')
value.set_editor_property('tooltip', 'Percentage removed from your normal master volume while enabled. 50% leaves half of your normal volume. Applies immediately.')
value.set_editor_property('default_value', 50)
value.set_editor_property('value', 50)
value.set_editor_property('widget_type', unreal.CP_IntegerWidgetType.CPI_SLIDER)
value.set_editor_property('min_value', 5)
value.set_editor_property('max_value', 95)
section.set_editor_property('section_properties', {'ReductionPercent': value})
cdo.set_editor_property('root_section', section)
unreal.EditorAssetLibrary.save_loaded_asset(bp, only_if_is_dirty=False)

action = asset('IA_ToggleReducer', ROOT + '/Input', unreal.InputAction, unreal.InputAction_Factory())
action.set_editor_property('value_type', unreal.InputActionValueType.BOOLEAN)
action.set_editor_property('consume_input', False)
action.set_editor_property('action_description', 'Toggle the master-volume reducer on or off')
settings = unreal.new_object(unreal.PlayerMappableKeySettings, outer=action, name='ToggleKeySettings')
settings.set_editor_property('name', 'InstantVolumeReducer.Toggle')
settings.set_editor_property('display_name', 'Toggle volume reducer')
action.set_editor_property('player_mappable_key_settings', settings)
unreal.EditorAssetLibrary.save_loaded_asset(action, only_if_is_dirty=False)

factory = unreal.DataAssetFactory()
factory.set_editor_property('data_asset_class', unreal.FGInputMappingContext)
context = asset('IMC_InstantVolumeReducer', ROOT + '/Input', unreal.FGInputMappingContext, factory)
context.set_editor_property('m_display_name', 'Instant Volume Reducer')
context.set_editor_property('m_menu_priority', 200)
context.unmap_all()
key = unreal.Key()
key.set_editor_property('key_name', 'F7')
context.map_key(action, key)
unreal.EditorAssetLibrary.save_loaded_asset(context, only_if_is_dirty=False)

module_factory = unreal.BlueprintFactory()
module_factory.set_editor_property('parent_class', unreal.InstantVolumeReducerGameInstanceModule)
module_bp = asset('RootInstance_InstantVolumeReducer', ROOT, unreal.Blueprint, module_factory)
module = unreal.get_default_object(module_bp.generated_class())
module.set_editor_property('root_module', True)
module.set_editor_property('mod_configurations', [bp.generated_class()])
module.set_editor_property('mapping_context', context)
module.set_editor_property('toggle_action', action)
unreal.EditorAssetLibrary.save_loaded_asset(module_bp, only_if_is_dirty=False)
unreal.log('IVR assets created and saved successfully')
